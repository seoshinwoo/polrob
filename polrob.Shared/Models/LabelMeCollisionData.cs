    public static PointF[] GetWorldPolygon(string label)
    {
        if (!SourcePolygons.TryGetValue(label, out var sourcePoints))
        {
            throw new ArgumentOutOfRangeException(nameof(label), label, "Unknown LabelMe collision label.");
        }

        var worldPoints = new PointF[sourcePoints.Length];
        for (var index = 0; index < sourcePoints.Length; index++)
        {
            worldPoints[index] = new PointF(
                sourcePoints[index].X * WorldScale,
                sourcePoints[index].Y * WorldScale);
        }

        return worldPoints;
    }
